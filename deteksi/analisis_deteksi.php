/*
|--------------------------------------------------------------------------
| Mengambil parameter LMS BB/PB atau BB/TB dengan interpolasi
|--------------------------------------------------------------------------
|
| Tabel WHO tersedia setiap 0,5 cm. Jika hasil pengukuran berada di antara
| dua titik tabel, L, M, dan S diinterpolasi secara linear.
*/

function ambilLmsBbPbTb(
    float $panjangTinggiBadan,
    int $umurBulan,
    string $jenisKelamin,
    array $tabelBbPbLakiLaki,
    array $tabelBbPbPerempuan,
    array $tabelBbTbLakiLaki,
    array $tabelBbTbPerempuan
): ?array {

    if (
        $panjangTinggiBadan <= 0
        || $umurBulan < 0
        || $umurBulan > 60
    ) {
        return null;
    }

    $jenisKelaminNormal = strtolower(
        trim($jenisKelamin)
    );

    $lakiLaki = in_array(
        $jenisKelaminNormal,
        [
            "laki-laki",
            "laki laki",
            "l",
            "male",
            "pria"
        ],
        true
    );

    $perempuan = in_array(
        $jenisKelaminNormal,
        [
            "perempuan",
            "p",
            "female",
            "wanita"
        ],
        true
    );

    if (!$lakiLaki && !$perempuan) {
        return null;
    }

    /*
    |----------------------------------------------------------------------
    | Pemilihan indeks
    |----------------------------------------------------------------------
    | < 24 bulan  : BB/PB (weight-for-length)
    | >= 24 bulan : BB/TB (weight-for-height)
    |
    | Ini mengikuti asumsi metode pengukuran berdasarkan umur karena tabel
    | pengukuran aplikasi belum memiliki kolom "cara ukur".
    |----------------------------------------------------------------------
    */

    if ($umurBulan < 24) {
        $tabel = $lakiLaki
            ? $tabelBbPbLakiLaki
            : $tabelBbPbPerempuan;
    } else {
        $tabel = $lakiLaki
            ? $tabelBbTbLakiLaki
            : $tabelBbTbPerempuan;
    }

    if (empty($tabel)) {
        return null;
    }

    $posisi = $panjangTinggiBadan * 2;

    $kunciMinimum = (int) min(array_keys($tabel));
    $kunciMaksimum = (int) max(array_keys($tabel));

    if (
        $posisi < $kunciMinimum
        || $posisi > $kunciMaksimum
    ) {
        return null;
    }

    $kunciBawah = (int) floor($posisi);
    $kunciAtas = (int) ceil($posisi);

    if (!isset($tabel[$kunciBawah])) {
        $kunciBawah++;
    }

    if (!isset($tabel[$kunciAtas])) {
        $kunciAtas--;
    }

    if (
        !isset($tabel[$kunciBawah])
        || !isset($tabel[$kunciAtas])
    ) {
        return null;
    }

    if ($kunciBawah === $kunciAtas) {
        return $tabel[$kunciBawah];
    }

    $fraksi =
        ($posisi - $kunciBawah)
        / ($kunciAtas - $kunciBawah);

    return [
        "L" =>
            $tabel[$kunciBawah]["L"]
            + (
                $tabel[$kunciAtas]["L"]
                - $tabel[$kunciBawah]["L"]
            ) * $fraksi,

        "M" =>
            $tabel[$kunciBawah]["M"]
            + (
                $tabel[$kunciAtas]["M"]
                - $tabel[$kunciBawah]["M"]
            ) * $fraksi,

        "S" =>
            $tabel[$kunciBawah]["S"]
            + (
                $tabel[$kunciAtas]["S"]
                - $tabel[$kunciBawah]["S"]
            ) * $fraksi,
    ];
}

/*
|--------------------------------------------------------------------------
| Menghitung Z-Score status gizi berdasarkan BB/PB atau BB/TB
|--------------------------------------------------------------------------
|
| Rumus LMS WHO:
| Z = [(y/M)^L - 1] / (L x S)
|
| y = berat badan (kg)
*/

function hitungZScoreBbPbTb(
    float $beratBadan,
    float $panjangTinggiBadan,
    int $umurBulan,
    string $jenisKelamin,
    array $tabelBbPbLakiLaki,
    array $tabelBbPbPerempuan,
    array $tabelBbTbLakiLaki,
    array $tabelBbTbPerempuan
): ?float {

    if ($beratBadan <= 0) {
        return null;
    }

    $lms = ambilLmsBbPbTb(
        $panjangTinggiBadan,
        $umurBulan,
        $jenisKelamin,
        $tabelBbPbLakiLaki,
        $tabelBbPbPerempuan,
        $tabelBbTbLakiLaki,
        $tabelBbTbPerempuan
    );

    if ($lms === null) {
        return null;
    }

    $l = (float) $lms["L"];
    $median = (float) $lms["M"];
    $koefisienVariasi = (float) $lms["S"];

    if (
        $median <= 0
        || $koefisienVariasi <= 0
    ) {
        return null;
    }

    if (abs($l) < 0.000001) {
        $zScore =
            log($beratBadan / $median)
            / $koefisienVariasi;
    } else {
        $zScore =
            (
                pow(
                    $beratBadan / $median,
                    $l
                )
                - 1
            )
            / ($l * $koefisienVariasi);
    }

    return round($zScore, 2);
}

